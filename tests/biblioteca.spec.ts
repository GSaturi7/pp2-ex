import { test, expect } from '@playwright/test';

test('CRUD, validações, filtros, persistência e exclusão de gênero', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('Nenhum livro.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Adicionar livro', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Título é obrigatório');
  await page.getByRole('button', { name: 'Gêneros', exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar gênero', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Nome é obrigatório');
  await page.getByLabel('Novo gênero', { exact: true }).fill('Romance de teste');
  await page.getByRole('button', { name: 'Adicionar gênero', exact: true }).click();
  await expect(page.locator('li.genero')).toContainText('Romance de teste');
  await page.getByRole('button', { name: 'Livros', exact: true }).click();
  await page.getByLabel('Título', { exact: true }).fill('Dom Casmurro');
  await page.getByRole('button', { name: 'Adicionar livro', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Autor é obrigatório');
  await page.getByLabel('Autor', { exact: true }).fill('Machado de Assis');
  await page.getByLabel('Páginas', { exact: true }).fill('256');
  await page.getByLabel('Gênero', { exact: true }).selectOption({ label: 'Romance de teste' });
  await page.getByRole('button', { name: 'Adicionar livro', exact: true }).click();
  await expect(page.locator('li.livro')).toContainText('Romance de teste');
  await expect(page.getByLabel('Título', { exact: true })).toHaveValue('');
  await page.getByLabel('Título', { exact: true }).fill('Outro livro');
  await page.getByLabel('Autor', { exact: true }).fill('Outra autora');
  await page.getByLabel('Gênero', { exact: true }).selectOption({ label: 'Romance de teste' });
  await page.getByRole('button', { name: 'Adicionar livro', exact: true }).click();
  await expect(page.locator('li.livro')).toHaveCount(2);
  await page.getByLabel('Buscar por título').fill('CASMURRO');
  await expect(page.locator('li.livro')).toHaveCount(1);
  await expect(page.getByText('1 de 2 livros', { exact: true })).toBeVisible();
  await page.getByLabel('Filtrar por gênero').selectOption('sem');
  await expect(page.getByText('Nenhum livro encontrado com esses filtros.')).toBeVisible();
  await page.getByLabel('Filtrar por gênero').selectOption('todos');
  await page.getByRole('checkbox').check();
  await expect(page.getByRole('checkbox')).toBeChecked();
  await page.getByRole('button', { name: 'Editar', exact: true }).click();
  await page.getByLabel('Título da edição').fill('');
  await page.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Título é obrigatório');
  await expect(page.getByLabel('Título da edição')).toBeVisible();
  await page.getByLabel('Título da edição').fill('Dom Casmurro revisado');
  await page.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dom Casmurro revisado' })).toBeVisible();
  await page.reload();
  await expect(page.locator('li.livro')).toHaveCount(2);
  await expect(page.getByRole('checkbox').first()).toBeChecked();
  await page.getByRole('button', { name: 'Gêneros', exact: true }).click();
  await page.getByRole('button', { name: 'Editar', exact: true }).click();
  await page.getByLabel('Nome do gênero').fill('Romance renomeado');
  await page.getByRole('button', { name: 'Salvar', exact: true }).click();
  await page.getByRole('button', { name: 'Livros', exact: true }).click();
  await expect(page.locator('li.livro').first()).toContainText('Romance renomeado');
  await expect(page.getByLabel('Gênero', { exact: true }).getByRole('option', { name: 'Romance renomeado' })).toHaveCount(1);
  await page.getByRole('button', { name: 'Gêneros', exact: true }).click();
  await page.getByRole('button', { name: 'Remover', exact: true }).click();
  await expect(page.getByText('Nenhum gênero.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Livros', exact: true }).click();
  await expect(page.locator('li.livro')).toHaveCount(2);
  await expect(page.locator('li.livro').first()).toContainText('Sem gênero');
  await expect(page.locator('li.livro').last()).toContainText('Sem gênero');
  await expect(page.getByLabel('Gênero', { exact: true }).locator('option')).toHaveCount(1);
  await page.getByRole('button', { name: 'Remover', exact: true }).first().click();
  await expect(page.locator('li.livro')).toHaveCount(1);
  await page.getByRole('button', { name: 'Remover', exact: true }).click();
  await expect(page.getByText('Nenhum livro.', { exact: true })).toBeVisible();
});

test('carregamento e falha de conexão', async ({ page }) => {
  await page.route('http://localhost:3001/**', async route => {
    await new Promise(resolve => setTimeout(resolve, 600));
    await route.abort('failed');
  });
  await page.goto('/');
  await expect(page.getByText('Carregando...', { exact: true })).toBeVisible();
  await expect(page.getByRole('alert')).toContainText('Failed to fetch');
});
